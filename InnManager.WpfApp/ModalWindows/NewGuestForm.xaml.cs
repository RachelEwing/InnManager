namespace InnManager.WpfApp.ModalWindows
{
    /// <summary>
    /// Interaction logic for NewGuestForm.xaml
    /// </summary>
    public partial class NewGuestForm : Window
    {
        public NewGuestForm()
        {
            InitializeComponent();
        }
        /// <summary>
        /// Converts data to a new employee or returns error
        /// </summary>
        /// <param name="sender"></param>
        /// <param name="e"></param>
        public void AddGuestClick(object sender, RoutedEventArgs e)
        {
            Guest guest = new Guest();
            var data = this.DataContext;
            if (data is Hotel h)
            {
                h.Guests.Add(guest);
            }
            DialogResult = true;
            this.Close();
        }
        public void CancelClick(object sender, RoutedEventArgs e)
        {
            DialogResult = false;
            this.Close();
        }
    }
}
